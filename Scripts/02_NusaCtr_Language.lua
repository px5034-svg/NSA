function NusaCtr_IsEnglish()
  return NusaCtr_Lang ~= "id"
end

--- Translate by English source string. Missing key → keep English.
function NusaCtr_T(en)
  en = tostring(en or "")
  if en == "" then return "" end
  if NusaCtr_IsEnglish() then return en end
  return ID[en] or en
end

function NusaCtr_ToggleLanguage()
  if NusaCtr_Lang == "id" then
    NusaCtr_Lang = "en"
  else
    NusaCtr_Lang = "id"
  end
  return NusaCtr_Lang
end

function NusaCtr_LangButtonLabel()
  if NusaCtr_IsEnglish() then
    return "Language: E"
  end
  return "Bahasa: ID"
end

